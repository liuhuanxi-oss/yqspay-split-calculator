import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const artifacts = resolve(root, 'artifacts'); await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], outside = [], consoleErrors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', item => { if (item.type() === 'error') consoleErrors.push(item.text()); });
  const base = process.env.TEST_URL || 'http://127.0.0.1:4319';
  const origin = new URL(base).origin;
  page.on('request', request => { if (new URL(request.url()).origin !== origin) outside.push(request.url()); });
  await page.goto(base);
  await page.getByRole('button', { name: '开始试算' }).click();
  await page.getByRole('status').filter({ hasText: '试算完成' }).waitFor();
  assert.match(await page.locator('#rows').innerText(), /49\.81/);
  assert.match(await page.locator('#rows').innerText(), /647\.53/);
  await page.screenshot({ path: resolve(artifacts, 'desktop.png'), fullPage: true });
  let pending = page.waitForEvent('download'); await page.getByRole('button', { name: '导出 JSON' }).click();
  let download = await pending; const jsonPath = resolve(artifacts, 'result.json'); await download.saveAs(jsonPath);
  const saved = JSON.parse(await readFile(jsonPath, 'utf8')); assert.equal(saved.feeCents, 380);
  pending = page.waitForEvent('download'); await page.getByRole('button', { name: '导出 CSV' }).click();
  download = await pending; const csvPath = resolve(artifacts, 'result.csv'); await download.saveAs(csvPath); assert.match(await readFile(csvPath, 'utf8'), /预计净额/);
  await page.locator('#fee-mode').selectOption('participant'); assert.equal(await page.locator('#export-json').isDisabled(), true);
  await page.getByRole('button', { name: '开始试算' }).click(); await page.getByRole('status').filter({ hasText: '有效的手续费承担方' }).waitFor();
  await page.locator('#fee-payer').selectOption('platform'); await page.getByRole('button', { name: '开始试算' }).click();
  assert.match(await page.locator('#rows').innerText(), /46\.20/);
  await page.locator('#fee-mode').selectOption('proportional'); await page.getByRole('button', { name: '开始试算' }).click();
  assert.match(await page.locator('#rows').innerText(), /0\.19/); assert.match(await page.locator('#rows').innerText(), /49\.81/);
  await page.locator('.party-value').first().fill('100'); await page.getByRole('button', { name: '开始试算' }).click();
  await page.getByRole('status').filter({ hasText: '超过分配基数' }).waitFor(); assert.equal(await page.locator('#export-csv').isDisabled(), true);
  await page.locator('#import').setInputFiles(jsonPath); await page.getByRole('status').filter({ hasText: '试算完成' }).waitFor(); assert.equal(await page.locator('#total').inputValue(), '1000.00');
  await page.locator('#import').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"total":false}') });
  await page.getByRole('status').filter({ hasText: '导入失败，原规则保留' }).waitFor(); assert.equal(await page.locator('#total').inputValue(), '1000.00');
  await page.getByRole('button', { name: '添加一方' }).click(); assert.equal(await page.locator('.party').count(), 4); assert.equal(await page.locator('#export-json').isDisabled(), true);
  await page.getByRole('button', { name: '删除此分配方' }).last().click(); assert.equal(await page.locator('.party').count(), 3);
  await page.locator('#preset').selectOption('fixed'); await page.getByRole('button', { name: '载入演示并试算' }).click(); assert.match(await page.locator('#rows').innerText(), /750\.00/);
  await page.locator('#preset').selectOption('rounding'); await page.getByRole('button', { name: '载入演示并试算' }).click(); assert.match(await page.locator('#rounding-note').innerText(), /甲方 \+1 分/);
  await page.locator('#preset').selectOption('platform'); await page.getByRole('button', { name: '载入演示并试算' }).click();
  await page.setViewportSize({ width: 390, height: 844 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: resolve(artifacts, 'mobile.png'), fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(consoleErrors, []); assert.deepEqual(outside, []);
  console.log('Browser checks passed: three fee modes, custom rule editing, oversubscription errors, payer validation, JSON round trip, CSV download, invalid import preservation, add/remove parties, fixed and rounding presets, stale-result reset, 390px layout, no console/page errors or external requests.');
} finally { await browser.close(); }
